CREATE OR REPLACE FUNCTION novel.acquire_session_lease(
  p_session_id UUID,
  p_lease_id UUID,
  p_stale_before TIMESTAMPTZ
)
RETURNS BOOLEAN
LANGUAGE SQL
AS $$
  WITH acquired AS (
    UPDATE novel.sessions
    SET processing_lease_id = p_lease_id,
        processing_started_at = now(),
        is_processing = true,
        updated_at = now()
    WHERE id = p_session_id
      AND (
        processing_lease_id IS NULL
        OR processing_started_at IS NULL
        OR processing_started_at < p_stale_before
      )
    RETURNING id
  )
  SELECT EXISTS (SELECT 1 FROM acquired);
$$;

CREATE OR REPLACE FUNCTION novel.release_session_lease(
  p_session_id UUID,
  p_lease_id UUID
)
RETURNS BOOLEAN
LANGUAGE SQL
AS $$
  WITH released AS (
    UPDATE novel.sessions
    SET processing_lease_id = NULL,
        processing_started_at = NULL,
        is_processing = false,
        updated_at = now()
    WHERE id = p_session_id
      AND processing_lease_id = p_lease_id
    RETURNING id
  )
  SELECT EXISTS (SELECT 1 FROM released);
$$;

CREATE OR REPLACE FUNCTION novel.claim_memory_jobs(
  p_now TIMESTAMPTZ,
  p_limit INTEGER
)
RETURNS SETOF novel.memory_jobs
LANGUAGE SQL
AS $$
  WITH selected AS (
    SELECT id
    FROM novel.memory_jobs
    WHERE status IN ('pending', 'failed')
      AND next_attempt_at <= p_now
    ORDER BY next_attempt_at, created_at, id
    FOR UPDATE SKIP LOCKED
    LIMIT GREATEST(p_limit, 0)
  )
  UPDATE novel.memory_jobs AS job
  SET status = 'running',
      updated_at = now()
  FROM selected
  WHERE job.id = selected.id
  RETURNING job.*;
$$;

CREATE OR REPLACE FUNCTION novel.prepare_session_memory_delete(
  p_session_id UUID
)
RETURNS BOOLEAN
LANGUAGE plpgsql
AS $$
BEGIN
  UPDATE novel.memory_jobs
  SET status = 'cancelled',
      updated_at = now()
  WHERE session_id = p_session_id
    AND status IN ('pending', 'failed');

  RETURN NOT EXISTS (
    SELECT 1
    FROM novel.memory_jobs
    WHERE session_id = p_session_id
      AND status = 'running'
  );
END;
$$;

