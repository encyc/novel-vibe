ALTER TABLE novel.sessions
  ADD COLUMN IF NOT EXISTS title_is_custom BOOLEAN NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS processing_lease_id UUID,
  ADD COLUMN IF NOT EXISTS processing_started_at TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS memory_status TEXT NOT NULL DEFAULT 'healthy',
  ADD COLUMN IF NOT EXISTS memory_ever_enabled BOOLEAN NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS last_opened_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT now();

ALTER TABLE novel.session_messages
  ADD COLUMN IF NOT EXISTS sequence BIGINT GENERATED BY DEFAULT AS IDENTITY,
  ADD COLUMN IF NOT EXISTS agent_id TEXT NOT NULL DEFAULT 'chief_editor',
  ADD COLUMN IF NOT EXISTS turn_id UUID,
  ADD COLUMN IF NOT EXISTS message JSONB,
  ADD COLUMN IF NOT EXISTS status TEXT NOT NULL DEFAULT 'complete',
  ADD COLUMN IF NOT EXISTS display BOOLEAN NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS metadata JSONB NOT NULL DEFAULT '{}',
  ADD COLUMN IF NOT EXISTS provider TEXT;

UPDATE novel.session_messages
SET display = role IN ('user', 'assistant'),
    metadata = metadata || '{"legacy":true}'::jsonb
WHERE turn_id IS NULL AND message IS NULL;

DO $$
DECLARE
  row_record RECORD;
  active_session UUID;
  active_turn UUID;
BEGIN
  FOR row_record IN
    SELECT id, session_id, role
    FROM novel.session_messages
    WHERE turn_id IS NULL
    ORDER BY session_id, timestamp, id
  LOOP
    IF active_session IS DISTINCT FROM row_record.session_id THEN
      active_session := row_record.session_id;
      active_turn := NULL;
    END IF;

    IF row_record.role = 'user' OR active_turn IS NULL THEN
      active_turn := gen_random_uuid();
    END IF;

    UPDATE novel.session_messages
    SET turn_id = active_turn
    WHERE id = row_record.id;

    IF row_record.role = 'assistant' THEN
      active_turn := NULL;
    END IF;
  END LOOP;
END
$$;

ALTER TABLE novel.session_messages
  ALTER COLUMN turn_id SET NOT NULL,
  ALTER COLUMN sequence SET NOT NULL;

UPDATE novel.sessions AS session
SET memory_ever_enabled = true
WHERE EXISTS (
  SELECT 1
  FROM novel.session_messages AS message
  WHERE message.session_id = session.id
);

CREATE TABLE IF NOT EXISTS novel.session_agent_state (
  session_id UUID NOT NULL REFERENCES novel.sessions(id) ON DELETE CASCADE,
  agent_id TEXT NOT NULL,
  summary TEXT,
  summary_through_sequence BIGINT,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (session_id, agent_id)
);

CREATE TABLE IF NOT EXISTS novel.memory_jobs (
