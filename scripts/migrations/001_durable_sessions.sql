  project_id UUID NOT NULL REFERENCES novel.projects(id) ON DELETE CASCADE,
  turn_id UUID NOT NULL,
  operation TEXT NOT NULL CHECK (operation IN ('capture')),
  payload JSONB NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'running', 'complete', 'failed', 'cancelled')),
  attempts INTEGER NOT NULL DEFAULT 0,
  next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_error TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS novel.memory_exclusions (
  project_id UUID NOT NULL REFERENCES novel.projects(id) ON DELETE CASCADE,
  deleted_session_id UUID NOT NULL,
  external_memory_id TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (project_id, external_memory_id)
