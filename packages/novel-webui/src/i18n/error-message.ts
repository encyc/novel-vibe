export function localizeApiError(error: unknown, fallbackKey = "errors.UNKNOWN"): string {
  if (error instanceof TypeError) return i18n.t("errors.NETWORK");
  if (error instanceof ApiError) {
    const code = error.code ?? (error.status === 401 ? "UNAUTHORIZED" : null);
    if (code && KNOWN_ERROR_CODES.has(code)) {
      return i18n.t(`errors.${code}`);
    }
  }
  return i18n.t(fallbackKey);
}
