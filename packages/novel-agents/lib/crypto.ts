/**
 * AES-256-GCM encryption for BYOK API keys. Ciphertext format:
 * `v1:<iv>:<ciphertext>:<authTag>` (base64url segments). The version prefix
 * leaves room for future key rotation without re-encrypting blindly.
 *
 * Any non-empty passphrase is accepted and hashed (SHA-256) into the AES key,
 * so operators don't have to mint a base64-aligned secret; strength comes
 * from the passphrase's entropy, so production should still use a random one.
 *
 * Key source. `BYOK_ENCRYPTION_KEY` is authoritative whenever it is set — that is
 * the only source in a hosted deployment, and a deployment without it stays
 * fail-closed (BYOK disabled). A local install has no operator to set one, so in
 * local mode a per-install secret is read from a user-owned file
 * (`NOVEL_VIBE_LOCAL_SECRET_FILE`, default `~/.novel-vibe/byok-encryption-key`),
 * generated on first use and written `0600`. The secret is never compiled into
 * the source and never leaves the machine.
 */
import { createCipheriv, createDecipheriv, createHash, randomBytes } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { isLocalMode } from "./local-mode.js";

const VERSION = "v1";

/** Points a local install at a different BYOK secret file. */
export const LOCAL_SECRET_FILE_ENV = "NOVEL_VIBE_LOCAL_SECRET_FILE";

const LOCAL_SECRET_DIR = ".novel-vibe";
const LOCAL_SECRET_FILENAME = "byok-encryption-key";

export class ByokCipherError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "ByokCipherError";
  }
}

/**
 * Where a local install keeps its generated BYOK secret.
 *
 * `NOVEL_VIBE_LOCAL_SECRET_FILE` wins when set; otherwise the secret lives in
 * `~/.novel-vibe/byok-encryption-key` so it is stable across restarts and
 * reinstall-scoped to the OS user.
 */
export function localByokSecretPath(env: NodeJS.ProcessEnv = process.env): string {
  const configured = env[LOCAL_SECRET_FILE_ENV]?.trim();
  return configured ? resolve(configured) : join(homedir(), LOCAL_SECRET_DIR, LOCAL_SECRET_FILENAME);
}

function localSecretError(path: string, error: unknown): ByokCipherError {
  const detail = error instanceof Error ? error.message : String(error);
  return new ByokCipherError(`Cannot use local BYOK secret at ${path}: ${detail}`);
}

/** Reads the local secret; null when the file is missing or empty. */
function readLocalSecret(path: string): string | null {
  let raw: string;
  try {
    raw = readFileSync(path, "utf8");
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") return null;
    throw localSecretError(path, error);
  }
  return raw.trim() || null;
}

/**
 * Reads the local secret, generating a random one on first use.
 *
 * Creation uses the exclusive `wx` flag so two processes starting together
 * converge on a single key instead of racing to overwrite each other; the loser
 * adopts what the winner wrote. Regenerating an existing secret would silently
 * orphan every stored ciphertext, so an existing non-empty file is always
 * authoritative.
 */
function readOrCreateLocalSecret(env: NodeJS.ProcessEnv): string {
  const path = localByokSecretPath(env);
  const existing = readLocalSecret(path);
  if (existing) return existing;

  const generated = randomBytes(32).toString("base64url");
  try {
    mkdirSync(dirname(path), { recursive: true, mode: 0o700 });
  } catch (error) {
    throw localSecretError(path, error);
  }
  try {
    writeFileSync(path, `${generated}\n`, { encoding: "utf8", mode: 0o600, flag: "wx" });
    return generated;
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== "EEXIST") throw localSecretError(path, error);
  }
  const raced = readLocalSecret(path);
  if (raced) return raced;
  // An empty leftover file cannot serve as a secret — replace it.
  try {
    writeFileSync(path, `${generated}\n`, { encoding: "utf8", mode: 0o600 });
  } catch (error) {
    throw localSecretError(path, error);
  }
  return generated;
}

/**
 * The BYOK encryption secret in effect, or null when none can be resolved.
 *
 * `BYOK_ENCRYPTION_KEY` always wins. Without it, only local mode falls back to
 * the generated file secret — a hosted deployment resolves to null and stays
 * fail-closed, so it can never pick up a stray local file.
 */
export function resolveByokEncryptionSecret(env: NodeJS.ProcessEnv = process.env): string | null {
  const configured = env.BYOK_ENCRYPTION_KEY?.trim();
  if (configured) return configured;
  if (!isLocalMode(env)) return null;
  return readOrCreateLocalSecret(env);
}

function encryptionKey(): Buffer {
  const raw = resolveByokEncryptionSecret();
  if (!raw) throw new ByokCipherError("BYOK_ENCRYPTION_KEY env var is required");
  return createHash("sha256").update(raw, "utf8").digest();
}

export function encryptByokSecret(plaintext: string): string {
  const iv = randomBytes(12);
  const cipher = createCipheriv("aes-256-gcm", encryptionKey(), iv);
  const ciphertext = Buffer.concat([cipher.update(plaintext, "utf8"), cipher.final()]);
  return [
    VERSION,
    iv.toString("base64url"),
    ciphertext.toString("base64url"),
    cipher.getAuthTag().toString("base64url"),
  ].join(":");
}

export function decryptByokSecret(payload: string): string {
  const [version, ivPart, dataPart, tagPart] = payload.split(":");
  if (version !== VERSION || !ivPart || !dataPart || !tagPart) {
    throw new ByokCipherError("Malformed encrypted payload");
  }
  try {
    const decipher = createDecipheriv("aes-256-gcm", encryptionKey(), Buffer.from(ivPart, "base64url"));
    decipher.setAuthTag(Buffer.from(tagPart, "base64url"));
    return Buffer.concat([
      decipher.update(Buffer.from(dataPart, "base64url")),
      decipher.final(),
    ]).toString("utf8");
  } catch {
    throw new ByokCipherError("Encrypted payload failed authentication");
  }
}
